def _options(correct, pool, seed):
    candidates=[x for x in pool if x != correct]
    rng=random.Random(seed)
    wrong=rng.sample(candidates,3)
    opts=wrong+[correct]
    rng.shuffle(opts)
    return opts, opts.index(correct)

def build_questions():
    out=[]
    country_data=[x for x in COUNTRIES if x[0] not in {"Канада", "Япония", "Израиль", "Индонезия", "Боливия", "Эсватини", "Бенин"}][:100]
    capitals=[c for c,_ in country_data]
    cities=[v for _,v in country_data]
    for idx,(country,capital) in enumerate(country_data):
        opts,ci=_options(capital,cities,1000+idx)
        out.append((f"Какова столица страны «{country}»?",opts,ci,"География"))
        opts,ci=_options(country,capitals,2000+idx)
        out.append((f"В какой стране находится столица {capital}?",opts,ci,"География"))
    names=[n for n,_ in ELEMENTS]
    symbols=[s for _,s in ELEMENTS]
    for idx,(name,symbol) in enumerate(ELEMENTS):
        if name != "Золото":
            opts,ci=_options(symbol,symbols,3000+idx)
            out.append((f"Какой химический символ у элемента «{name}»?",opts,ci,"Химия"))
        number=str(idx+1)
        nums=[str(i) for i in range(1,101)]
        opts,ci=_options(number,nums,4000+idx)
        out.append((f"Какой порядковый номер у химического элемента «{name}»?",opts,ci,"Химия"))
    out.extend(EXTRA[:50])
    # Дополняем исключённый повтор вопросом из отдельной темы.
